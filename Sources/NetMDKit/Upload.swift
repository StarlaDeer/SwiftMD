import CommonCrypto
import Foundation

public enum Wireformat: Int, Sendable {
    case pcm = 0x00
    case l105kbps = 0x90
    case lp2 = 0x94
    case lp4 = 0xa8

    /// Bytes per frame as sent over USB.
    var frameSize: Int {
        switch self {
        case .pcm: return 2048
        case .lp2: return 192
        case .l105kbps: return 152
        case .lp4: return 96
        }
    }

    var discFormat: DiscFormat {
        switch self {
        case .pcm: return .spStereo
        case .lp2, .l105kbps: return .lp2
        case .lp4: return .lp4
        }
    }
}

// MARK: - EKB (enabling key block): unlocks the device's secure session

struct EKB {
    let rootKey: [UInt8]
    let ekbID: UInt32
    let keychain: [[UInt8]]
    let depth: Int
    let signature: [UInt8]

    static let openSource = EKB(
        rootKey: [0x12, 0x34, 0x56, 0x78, 0x9a, 0xbc, 0xde, 0xf0, 0x0f, 0xed, 0xcb, 0xa9, 0x87, 0x65, 0x43, 0x21],
        ekbID: 0x2642_2642,
        keychain: [
            [0x25, 0x45, 0x06, 0x4d, 0xea, 0xca, 0x14, 0xf9, 0x96, 0xbd, 0xc8, 0xa4, 0x06, 0xc2, 0x2b, 0x81],
            [0xfb, 0x60, 0xbd, 0xdd, 0x0d, 0xbc, 0xab, 0x84, 0x8a, 0x00, 0x5e, 0x03, 0x19, 0x4d, 0x3e, 0xda],
        ],
        depth: 9,
        signature: [
            0x8f, 0x2b, 0xc3, 0x52, 0xe8, 0x6c, 0x5e, 0xd3, 0x06, 0xdc, 0xae, 0x18,
            0xd2, 0xf3, 0x8c, 0x7f, 0x89, 0xb5, 0xe1, 0x85, 0x55, 0xa1, 0x05, 0xea,
        ]
    )

    // EKB generated by Sir68k, for decks whose leaf ID was corrupted.
    static let corruptedDeck = EKB(
        rootKey: Array("WMDPWMDPMiniDisc".utf8),
        ekbID: 0x1337_1337,
        keychain: [[0xb1, 0xd4, 0xaf, 0xfa, 0x80, 0xa0, 0xc9, 0x03, 0xc2, 0x58, 0x4b, 0x1b, 0x44, 0xaf, 0xc4, 0xa6]],
        depth: 9,
        signature: [
            0x6c, 0x2b, 0xc2, 0x8c, 0x45, 0x2b, 0x54, 0xf1, 0xc3, 0x59, 0x72, 0x3b,
            0xe3, 0x19, 0x1f, 0x55, 0x17, 0x25, 0x64, 0x0e, 0x65, 0x8c, 0x81, 0x0b,
        ]
    )

    static func forDevice(leafID: [UInt8], vendorID: Int, productID: Int) -> EKB {
        // VID = Sony, PID = decks (JB980 / JE780 / NT1)
        if leafID.allSatisfy({ $0 == 0xff }), vendorID == 0x054c, productID == 0x0081 {
            return .corruptedDeck
        }
        return .openSource
    }
}

// MARK: - Track data

/// Audio ready to send: SP as 16-bit big-endian stereo PCM, LP2/LP4 as raw ATRAC3 frames.
public struct MDTrack: Sendable {
    public var title: String
    public var fullWidthTitle: String?
    public var format: Wireformat
    public var data: [UInt8]
    /// Disc format to record as; nil uses the format's default (SP stereo for PCM).
    public var discFormat: DiscFormat?

    public init(title: String, fullWidthTitle: String? = nil, format: Wireformat, data: [UInt8], discFormat: DiscFormat? = nil) {
        self.title = title
        self.fullWidthTitle = fullWidthTitle
        self.format = format
        self.data = data
        self.discFormat = discFormat
    }

    /// Data length padded up to a whole frame.
    var totalSize: Int {
        let remainder = data.count % format.frameSize
        return remainder == 0 ? data.count : data.count + format.frameSize - remainder
    }

    var frameCount: Int { totalSize / format.frameSize }

    static let contentID: [UInt8] = [
        0x01, 0x0f, 0x50, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x48,
        0xa2, 0x8d, 0x3e, 0x1a, 0x3b, 0x0c, 0x44, 0xaf, 0x2f, 0xa0,
    ]
    /// Key encryption key: the device uses it to recover the data key sent with the track.
    static let kek: [UInt8] = [0x14, 0xe3, 0x83, 0x4e, 0xe2, 0xd3, 0xcc, 0xa5]

    /// The bytes written over bulk USB: a 24-byte header (length, wrapped data key, IV)
    /// followed by the data, DES-CBC encrypted with a random key.
    func encryptedStream(dataKey: [UInt8] = randomBytes(8)) throws -> [UInt8] {
        let padded = data + [UInt8](repeating: 0, count: totalSize - data.count)
        let iv = [UInt8](repeating: 0, count: 8)
        // The header carries the data key "decrypted" under the KEK; the device encrypts it back.
        let wrappedKey = try des(CCOperation(kCCDecrypt), key: Self.kek, .ecb, dataKey)
        let encrypted = try des(CCOperation(kCCEncrypt), key: dataKey, .cbc(iv: iv), padded)
        let length = UInt32(totalSize)
        let lengthBytes: [UInt8] = [UInt8(length >> 24), UInt8((length >> 16) & 0xff), UInt8((length >> 8) & 0xff), UInt8(length & 0xff)]
        return [0, 0, 0, 0] + lengthBytes + wrappedKey + iv + encrypted
    }
}

public enum UploadFailure: Error, Equatable, CustomStringConvertible {
    /// The device received the whole track, then refused to record it.
    case recorderRejectedTrack
    case deviceNotReady(statusCode: Int)

    public var description: String {
        switch self {
        case .recorderRejectedTrack:
            return "The recorder received the track but couldn't record it, so nothing was added. "
                + "This happens with a worn or faulty disc; try another disc. The recorder may show ERROR: "
                + "unplug it and press stop to clear it."
        case .deviceNotReady(let code):
            return String(format: "The recorder isn't ready (status 0x%04x). If it shows ERROR, unplug it and press stop, then try again.", code)
        }
    }
}

public struct UploadProgress: Sendable {
    public var writtenBytes: Int
    public var totalBytes: Int
}

// MARK: - Secure session commands

extension NetMDInterface {
    public func acquire() async throws {
        let reply = try await sendQuery(formatQuery("ff 010c ffff ffff ffff ffff ffff ffff"))
        _ = try scanQuery(reply, "ff 010c ffff ffff ffff ffff ffff ffff")
    }

    public func release() async throws {
        let reply = try await sendQuery(formatQuery("ff 0100 ffff ffff ffff ffff ffff ffff"))
        _ = try scanQuery(reply, "ff 0100 ffff ffff ffff ffff ffff ffff")
    }

    func disableNewTrackProtection(_ value: Int) async throws {
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 2b ff %w", .init(value)))
        _ = try scanQuery(reply, "1800 080046 f0030103 2b 00 %?%?")
    }

    func enterSecureSession() async throws {
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 80 ff"))
        _ = try scanQuery(reply, "1800 080046 f0030103 80 00")
    }

    func leaveSecureSession() async throws {
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 81 ff"))
        _ = try scanQuery(reply, "1800 080046 f0030103 81 00")
    }

    func getLeafID() async throws -> [UInt8] {
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 11 ff"))
        return try scanQuery(reply, "1800 080046 f0030103 11 00 %*")[0].bytes
    }

    func sendKeyData(_ ekb: EKB) async throws {
        precondition(ekb.keychain.allSatisfy { $0.count == 16 } && (1...63).contains(ekb.depth) && ekb.signature.count == 24)
        let dataBytes = 16 + 16 * ekb.keychain.count + 24
        let reply = try await sendQuery(formatQuery(
            "1800 080046 f0030103 12 ff %w 0000 %w %d %d %d 00000000 %* %*",
            .init(dataBytes), .init(dataBytes), .init(ekb.keychain.count), .init(ekb.depth), .init(ekb.ekbID),
            .bytes(ekb.keychain.flatMap { $0 }), .bytes(ekb.signature)
        ))
        _ = try scanQuery(reply, "1800 080046 f0030103 12 01 %?%? %?%?%?%?")
    }

    func sessionKeyExchange(hostNonce: [UInt8]) async throws -> [UInt8] {
        precondition(hostNonce.count == 8)
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 20 ff 000000 %*", .bytes(hostNonce)))
        // '20 00' => '20 %?' - Fix for Panasonic SJ-MR270
        return try scanQuery(reply, "1800 080046 f0030103 20 %? 000000 %#")[0].bytes
    }

    func sessionKeyForget() async throws {
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 21 ff 000000"))
        _ = try scanQuery(reply, "1800 080046 f0030103 21 00 000000")
    }

    func setupDownload(contentID: [UInt8], keyEncryptionKey: [UInt8], sessionKey: [UInt8]) async throws {
        precondition(contentID.count == 20 && keyEncryptionKey.count == 8 && sessionKey.count == 8)
        let message = [1, 1, 1, 1] + contentID + keyEncryptionKey
        let encrypted = try des(CCOperation(kCCEncrypt), key: sessionKey, .cbc(iv: [UInt8](repeating: 0, count: 8)), message)
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 22 ff 0000 %*", .bytes(encrypted)))
        _ = try scanQuery(reply, "1800 080046 f0030103 22 00 0000")
    }

    func commitTrack(_ track: Int, sessionKey: [UInt8]) async throws {
        let authentication = try des(CCOperation(kCCEncrypt), key: sessionKey, .ecb, [UInt8](repeating: 0, count: 8))
        let reply = try await sendQuery(formatQuery("1800 080046 f0030103 48 ff 00 1001 %w %*", .init(track), .bytes(authentication)))
        _ = try scanQuery(reply, "1800 080046 f0030103 48 00 00 1001 %?%?")
    }

    /// Sends a track's encrypted data. Returns the new track's index.
    func sendTrack(_ track: MDTrack, discFormat: DiscFormat, progress: (@Sendable (UploadProgress) -> Void)?) async throws -> Int {
        let stream = try track.encryptedStream()
        let totalBytes = stream.count

        // The whole exchange (command, bulk data, final reply) must not be interleaved with other queries.
        await lock()
        defer { unlock() }

        await uninterruptibleSleep(.milliseconds(200)) // The sharps are slow...
        try sendCommand(formatQuery(
            "1800 080046 f0030103 28 ff 000100 1001 ffff 00 %b %b %d %d",
            .init(track.format.rawValue), .init(discFormat.rawValue), .init(track.frameCount), .init(totalBytes)
        ))
        _ = try scanQuery(try await readReply(acceptInterim: true), "1800 080046 f0030103 28 00 000100 1001 %?%? 00 %*")
        await uninterruptibleSleep(.milliseconds(200))

        var written = 0
        progress?(UploadProgress(writtenBytes: 0, totalBytes: totalBytes))
        // Once started, a transfer always runs to the end: stopping midway would leave the
        // device waiting for data. Cancelling an upload takes effect between tracks.
        while written < totalBytes {
            let chunk = Array(stream[written..<min(written + Self.bulkChunkSize, totalBytes)])
            try netMD.writeBulk(chunk)
            written += chunk.count
            if written % Self.progressInterval == 0 || written == totalBytes {
                progress?(UploadProgress(writtenBytes: written, totalBytes: totalBytes))
            }
        }

        // The device finishes writing to the disc before it replies, which can take a while.
        let reply = try await readReply(patient: true)
        _ = try netMD.getReplyLength()
        let res = try scanQuery(reply, "1800 080046 f0030103 28 00 000100 1001 %w 00 %?%? %?%?%?%? %?%?%?%? %*")
        return res[0].int
    }

    /// USB writes of 1 KiB, as Web MiniDisc sends them (its packets are 0x400 bytes, the first being
    /// the 24-byte header plus 1000 bytes of data). An MZ-N910 rejected the same data sent in 64 KiB writes.
    static let bulkChunkSize = 0x400
    static let progressInterval = 0x10000
}

// MARK: - Session

/// A secure session for sending one or more tracks. Port of netmd-js `MDSession`
/// plus `prepareDownload`, as Web MiniDisc's prepareUpload/upload/finalizeUpload use them.
public final class UploadSession: @unchecked Sendable {
    // Only used from one upload task at a time.
    private let device: NetMDInterface
    private var sessionKey: [UInt8]?

    init(device: NetMDInterface) {
        self.device = device
    }

    public static func start(on device: NetMDInterface) async throws -> UploadSession {
        // The device may still be busy with the previous track; wait until it's ready.
        var attempts = 0
        while true {
            let status = try await device.getDeviceStatus()
            if status.state == .ready || status.state == .discBlank { break }
            attempts += 1
            guard attempts < 150 else { throw UploadFailure.deviceNotReady(statusCode: status.operatingStatusCode) }
            await uninterruptibleSleep(.milliseconds(200))
        }
        // Assume there wasn't anything to finalize if these fail.
        try? await device.sessionKeyForget()
        try? await device.leaveSecureSession()

        try await device.acquire()
        try? await device.disableNewTrackProtection(1) // On Sharp devices this doesn't work anyway.

        let session = UploadSession(device: device)
        try await session.open()
        return session
    }

    private func open() async throws {
        try await device.enterSecureSession()
        let leafID = try await device.getLeafID()
        let ekb = EKB.forDevice(leafID: leafID, vendorID: device.vendorID, productID: device.productID)
        try await device.sendKeyData(ekb)
        let hostNonce = randomBytes(8)
        let deviceNonce = try await device.sessionKeyExchange(hostNonce: hostNonce)
        sessionKey = try retailMAC(key: ekb.rootKey, value: hostNonce + deviceNonce)
    }

    /// Sends one track and titles it. Returns the new track's index.
    @discardableResult
    public func send(_ track: MDTrack, progress: (@Sendable (UploadProgress) -> Void)? = nil) async throws -> Int {
        guard let sessionKey else { throw NetMDError.rejected("Upload session is closed") }
        try await device.setupDownload(contentID: MDTrack.contentID, keyEncryptionKey: MDTrack.kek, sessionKey: sessionKey)
        let index: Int
        do {
            index = try await device.sendTrack(track, discFormat: track.discFormat ?? track.format.discFormat, progress: progress)
        } catch NetMDError.rejected {
            // Seen with a worn disc on an MZ-N910: all data accepted, then a rejection minutes later.
            throw UploadFailure.recorderRejectedTrack
        }
        try await device.setTrackTitle(index, track.title)
        if let fullWidthTitle = track.fullWidthTitle, !fullWidthTitle.isEmpty {
            try await device.setTrackTitle(index, fullWidthTitle, wchar: true)
        }
        try await device.commitTrack(index, sessionKey: sessionKey)
        return index
    }

    /// Sends `count` tracks in one session, asking `prepare` for each just before sending it.
    /// Stops between tracks if the task is cancelled. `progress` receives the track's position.
    public static func upload(
        count: Int,
        to device: NetMDInterface,
        prepare: @Sendable (Int) async throws -> MDTrack,
        progress: (@Sendable (Int, UploadProgress) -> Void)? = nil
    ) async throws {
        let session = try await start(on: device)
        do {
            for i in 0..<count {
                if Task.isCancelled { break }
                let track = try await prepare(i)
                try await session.send(track) { progress?(i, $0) }
            }
        } catch {
            await session.close()
            throw error
        }
        await session.close()
    }

    public func close() async {
        if sessionKey != nil {
            try? await device.sessionKeyForget()
            sessionKey = nil
        }
        try? await device.leaveSecureSession()
        try? await device.release()
    }
}
